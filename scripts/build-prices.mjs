// Builds docs/src/prices.js, the price snapshot that ships inside the app, from the town file
// of София in docs/data/prices (made by scripts/fetch-prices.mjs). Run it when a release is cut:
//
//   node scripts/fetch-prices.mjs && node scripts/build-prices.mjs --apply
//
// The app shows today's file for the person's town when it can load it; the snapshot is what
// it counts with on the very first start without a connection. The reference price of a
// product (the fourth field of its row in the catalog) is the median across the chains here,
// and tests/prices.test.js keeps the two equal: with --apply the catalog rows are updated too.
import fs from 'node:fs';

const SOURCE = 'docs/data/prices/68134.json';
const data = JSON.parse(fs.readFileSync(SOURCE, 'utf8'));

const cents = (n) => Math.round(n * 100) / 100;
const median = (list) => {
  const s = list.slice().sort((a, b) => a - b);
  return s.length % 2 ? s[(s.length - 1) / 2] : (s[s.length / 2 - 1] + s[s.length / 2]) / 2;
};

const stores = {};
const reference = {};
for (const [key, chains] of Object.entries(data.products)) {
  stores[key] = Object.fromEntries(Object.entries(chains).map(([chain, entry]) => [chain, entry[0]]));
  reference[key] = cents(median(Object.values(stores[key])));
}

const lines = Object.entries(stores)
  .map(
    ([key, perStore]) =>
      `  ${key}: ${JSON.stringify(perStore).replace(/"/g, "'").replace(/,/g, ', ').replace(/:/g, ': ')},`,
  )
  .join('\n');
const out = `// Generated by scripts/build-prices.mjs from ${SOURCE}. Do not edit by hand.
// The price of our pack of a product in each chain, in euro: the cheapest matching product in
// the chain's typical store in ${data.place}, from the open data of the public price portal of
// the Consumer Protection Commission (kolkostruva.bg).
export const PRICE_SOURCE = Object.freeze({
  name: 'портала „Колко струва“ на КЗП',
  place: '${data.place}',
  date: '${data.date}',
  shown: '${data.date.split('-').reverse().join('.')}',
  url: 'https://kolkostruva.bg',
});

export const STORE_PRICES = Object.freeze({
${lines}
});

/** Median across the chains: the price used when the store has no figure of its own. */
export const REFERENCE_PRICES = Object.freeze(${JSON.stringify(reference, null, 2).replace(/"/g, "'")});
`;
fs.writeFileSync('docs/src/prices.js', out);
console.log(`docs/src/prices.js: ${Object.keys(stores).length} products, ${data.place}, ${data.date}`);

if (process.argv.includes('--apply')) {
  // A catalog row looks like  key: ['Име', 1000, 'г', 2.69, [...], false]  or
  // PRODUCTS.key = ['Име', 200, 'г', 2.3, ...]: only the fourth field changes.
  let changed = 0;
  for (const file of ['docs/src/catalog.js', 'docs/src/products-more.js']) {
    let source = fs.readFileSync(file, 'utf8');
    for (const [key, price] of Object.entries(reference)) {
      const row = new RegExp(
        `((?:^|[\\s{,.])${key}(?::| =)\\s*\\[\\s*'[^']*',\\s*[\\d.]+,\\s*'[^']*',\\s*)([\\d.]+)`,
        'm',
      );
      const match = source.match(row);
      if (!match || Number(match[2]) === price) continue;
      source = source.replace(row, `$1${price}`);
      changed++;
    }
    fs.writeFileSync(file, source);
  }
  console.log(`catalog: ${changed} reference prices updated`);
}
