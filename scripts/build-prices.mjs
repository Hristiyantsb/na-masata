// Builds docs/src/prices.js from a price snapshot of the public portal kolkostruva.bg
// (Consumer Protection Commission). Run: node scripts/build-prices.mjs [snapshot.json]
//
// For every chain the portal lists the lowest price of a product group. To keep one-day
// promotions from setting the number, the higher of today's and yesterday's price is used.
// The reference price of a product is the median across the chains that reported it.
import fs from 'node:fs';
import path from 'node:path';

const snapshot = process.argv[2] || 'project/prices/kzp-sofia-2026-11-10.json';
const data = JSON.parse(fs.readFileSync(snapshot, 'utf8'));

// product key -> [portal set, our pack as a share of the portal unit]
// A share of 1 means the portal pack is taken as our pack (a loaf, a 400-500 g cup, a 1 kg bag).
export const MAP = {
  bread: [1, 1],
  phyllo: [5, 1],
  milk: [6, 1],
  yogurt: [7, 1],
  cheese: [8, 0.4],
  kashkaval: [10, 0.4],
  butter: [12, 1],
  cottage: [13, 0.4],
  chicken: [16, 0.5],
  chickenleg: [17, 1],
  pork: [18, 1],
  beef: [24, 0.5],
  mince: [25, 0.5],
  mackerel: [29, 0.5],
  bean: [33, 0.5],
  lentil: [34, 0.5],
  rice: [35, 1],
  pasta: [37, 1],
  sugar: [38, 1],
  salt: [39, 1],
  flour: [40, 1],
  oil: [42, 1],
  oliveoil: [43, 0.5],
  vinegar: [44, 1],
  redbean: [46, 1],
  canned: [48, 1],
  lutenitsa: [49, 1],
  lemon: [50, 0.5],
  orange: [51, 1],
  banana: [52, 1],
  apple: [53, 1],
  tomato: [54, 1],
  onion: [55, 1],
  carrot: [56, 1],
  cabbage: [57, 1.5],
  cucumber: [58, 1],
  garlic: [59, 0.1],
  mushroom: [60, 0.5],
  potato: [61, 2],
  olives: [62, 0.2],
};

const cents = (n) => Math.round(n * 100) / 100;
const median = (list) => {
  const s = list.slice().sort((a, b) => a - b);
  return s.length % 2 ? s[(s.length - 1) / 2] : (s[s.length / 2 - 1] + s[s.length / 2]) / 2;
};

const stores = {};
const reference = {};
for (const [key, [set, share]] of Object.entries(MAP)) {
  const entry = data.sets[set];
  if (!entry) throw Error(`No set ${set} for ${key}`);
  const perStore = {};
  for (const [store, [today, yesterday]] of Object.entries(entry.chains)) {
    const price = Math.max(today ?? yesterday, yesterday ?? today);
    if (Number.isFinite(price)) perStore[store] = cents(price * share);
  }
  stores[key] = perStore;
  reference[key] = cents(median(Object.values(perStore)));
}

const lines = Object.entries(stores)
  .map(([key, perStore]) => `  ${key}: ${JSON.stringify(perStore).replace(/"/g, "'").replace(/,/g, ', ').replace(/:/g, ': ')},`)
  .join('\n');
const out = `// Generated by scripts/build-prices.mjs from ${path.basename(snapshot)}. Do not edit by hand.
// Lowest price of the product in each chain, for our pack size, in euro.
// Source: the public portal of the Consumer Protection Commission (kolkostruva.bg), ${data.place}.
export const PRICE_SOURCE = Object.freeze({
  name: 'портала „Колко струва“ на КЗП',
  place: '${data.place}',
  date: '${data.date}',
  shown: '${data.date.split('-').reverse().join('.')}',
  url: 'https://kolkostruva.bg',
});

export const STORE_PRICES = Object.freeze({
${lines}
});

/** Median across the chains: the price used when the store has no figure of its own. */
export const REFERENCE_PRICES = Object.freeze(${JSON.stringify(reference, null, 2).replace(/"/g, "'")});
`;
fs.writeFileSync('docs/src/prices.js', out);
console.log(`docs/src/prices.js: ${Object.keys(stores).length} products from ${data.place}, ${data.date}`);
for (const [key, value] of Object.entries(reference)) console.log(key.padEnd(12), String(value).padStart(6), JSON.stringify(stores[key]));
